def t(lang: str, key: str, **kwargs) -> str:
    """Module-level translator. Falls back to English if key missing.

    Used by helper modules that don't carry a self.ui_language reference.
    The main GUI's WhisperGUI.t() method continues to consult UI_TEXT directly
    for backward compatibility.
    """
    language_map = UI_TEXT.get(lang) or UI_TEXT["en"]
    text = language_map.get(key) or UI_TEXT["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text
